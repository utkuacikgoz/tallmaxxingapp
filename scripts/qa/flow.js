const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const output = process.env.QA_OUTPUT || 'artifacts/qa';
fs.mkdirSync(output, { recursive: true });
const scheme = process.argv[2] || 'light';
assert.ok(['light', 'dark'].includes(scheme), 'Use light or dark');
const prefix = scheme === 'dark' ? 'D' : 'L';
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: scheme, isMobile: true, hasTouch: true });
  await ctx.addInitScript(() => {
    Object.defineProperty(navigator, 'share', { configurable: true, value: async ({ text }) => { window.__qaSharedData = text; } });
  });
  const page = await ctx.newPage();
  page.setDefaultTimeout(10000);
  const logs = [];
  try {
  page.on('console', (m) => { if (m.type() === 'error') logs.push(`[error] ${m.text().slice(0, 300)}`); });
  page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
  const shot = async (name, wait = 700) => { await page.waitForTimeout(wait); await page.screenshot({ path: path.join(output, `${prefix}-${name}.png`) }); };
  const tap = async (id) => { console.log('tap', id); await page.getByTestId(id).first().click(); };
  await page.goto('http://localhost:8099/', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1500);
  await shot('01-welcome');
  await tap('welcome-start'); await shot('02-role');
  await tap('role-parent'); await page.waitForTimeout(600); await shot('03-sex');
  await tap('sex-male'); await page.waitForTimeout(700); await shot('04-birth');
  await page.getByRole('button', { name: 'Enter date with keyboard instead' }).click();
  await page.getByTestId('birth-typed').fill(`05${new Date().getFullYear() - 13}`);
  await shot('04b-birth-touched', 900);
  await tap('birth-continue'); await page.waitForTimeout(800);
  await page.getByTestId('height-unit').getByText('cm', { exact: true }).click();
  await page.getByTestId('height-field').fill('300'); await shot('05a-height-invalid', 400);
  assert.equal(await page.getByTestId('height-continue').getAttribute('aria-disabled'), 'true');
  await page.getByTestId('height-field').fill('152'); await shot('05-height', 400);
  await tap('height-continue'); await page.waitForTimeout(800);
  await page.getByTestId('weight-unit').getByText('kg', { exact: true }).click();
  await page.getByTestId('weight-field').fill('42'); await shot('06-weight', 400);
  await tap('weight-continue'); await page.waitForTimeout(900);
  await page.getByTestId('parent-mother').fill('163');
  await page.getByTestId('parent-father').fill('178'); await shot('07-parents', 400);
  await tap('parents-continue'); await page.waitForTimeout(900);
  await shot('08-puberty');
  await tap('puberty-grewALot'); await tap('puberty-voice'); await shot('08b-puberty-selected', 300);
  await tap('puberty-continue'); await page.waitForTimeout(800); await shot('09-sleep');
  await tap('sleep-8-9'); await page.waitForTimeout(800); await shot('10-goal');
  await tap('goal-fullHeight'); await page.waitForTimeout(800); await shot('11-research');
  await tap('see-result'); await shot('12-loader', 1500);
  await page.waitForTimeout(2600); await shot('13-result', 1800);
  assert.equal(await page.getByTestId('paywall').count(), 0);
  await page.getByTestId('result-hero').waitFor({ state: 'visible' });
  await page.mouse.wheel(0, 900); await shot('13b-result-scrolled', 600);
  await page.mouse.wheel(0, 1600); await shot('13c-result-bottom', 600);
  await tap('get-plan'); await shot('14-paywall', 1500);
  await page.getByTestId('paywall-close').waitFor({ state: 'visible' });
  await tap('plan-weekly'); await shot('14b-paywall-weekly', 400);
  await tap('plan-annual'); await tap('trial-toggle'); await shot('14c-paywall-trial', 400);
  await tap('paywall-close'); await page.waitForTimeout(800);
  await tap('result-share'); await shot('15-share', 1200);
  await page.getByRole('button', { name: 'Close', exact: true }).click(); await page.waitForTimeout(800);
  await tap('get-plan'); await page.waitForTimeout(1200);
  await tap('paywall-cta'); await page.waitForTimeout(2200); await shot('16-success');
  await tap('bedtime-21:30'); await shot('16b-success-picked', 300);
  await tap('start-plan');
  await page.getByTestId('today').waitFor({ state: 'visible' });
  await shot('17-today', 1800);
  await page.locator('[data-testid^="habit-"]').first().click();
  const habits = page.locator('[data-testid^="habit-"]');
  for (let i = 1; i < 3; i++) await habits.nth(i).click();
  await shot('17b-today-streak', 600);
  await page.goto('http://localhost:8099/growth', { waitUntil: 'networkidle' }); await page.getByTestId('growth').waitFor({ state: 'visible' }); await shot('18-growth', 1500);
  const measurementRows = () => page.getByTestId('growth').locator('[data-testid^="measurement-"]');
  await tap('growth-add');
  await page.getByTestId('log-height').fill('153');
  await page.getByTestId('log-weight').fill('43');
  await tap('log-add');
  await measurementRows().filter({ hasText: '153' }).waitFor({ state: 'visible' });
  assert.equal(await measurementRows().count(), 2, 'a saved measurement must update the mounted growth list');
  await page.reload({ waitUntil: 'networkidle' });
  await measurementRows().filter({ hasText: '153' }).waitFor({ state: 'visible' });
  assert.equal(await measurementRows().count(), 2, 'measurements must survive a reload');
  await page.goto('http://localhost:8099/log?replace=1', { waitUntil: 'networkidle' });
  await page.getByTestId('log-height').fill('154');
  await tap('log-add');
  await page.getByText('Measurement added', { exact: true }).waitFor({ state: 'visible' });
  await page.goto('http://localhost:8099/growth', { waitUntil: 'networkidle' });
  await measurementRows().filter({ hasText: '154' }).waitFor({ state: 'visible' });
  assert.equal(await measurementRows().count(), 1, 'replaceSingle must commit both the delete and replacement insert');
  await page.goto('http://localhost:8099/plan', { waitUntil: 'networkidle' }); await page.getByTestId('plan').waitFor({ state: 'visible' }); await shot('19-plan', 1500);
  await page.goto('http://localhost:8099/family', { waitUntil: 'networkidle' }); await page.getByTestId('family').waitFor({ state: 'visible' }); await shot('20-family', 1500);
  await page.getByText('Export All Data', { exact: true }).click();
  await page.waitForFunction(() => typeof window.__qaSharedData === 'string');
  const exported = JSON.parse(await page.evaluate(() => window.__qaSharedData));
  assert.equal(exported.children.length, 1);
  assert.equal(exported.measurements.length, 1);
  assert.equal(exported.measurements[0].heightCm, 154, 'export must read the committed replacement measurement');
  assert.equal(exported.habitChecks.filter((habit) => habit.done).length, 3, 'habit writes must persist across navigation');
  await page.mouse.wheel(0, 1200); await shot('20b-family-scrolled', 600);
  await page.goto('http://localhost:8099/log', { waitUntil: 'networkidle' }); await shot('21-log', 1500);
  await page.goto('http://localhost:8099/method', { waitUntil: 'networkidle' }); await shot('22-method', 1500);
  await page.goto('http://localhost:8099/share?milestone=7', { waitUntil: 'networkidle' });
  const milestone = page.getByTestId('milestone-card');
  await milestone.waitFor({ state: 'visible' });
  await milestone.screenshot({ path: path.join(output, `${prefix}-23-milestone-story.png`) });
  assert.ok(!(await milestone.textContent()).includes('cm'), 'Milestone must not include body measurements');
  await tap('milestone-square');
  await milestone.screenshot({ path: path.join(output, `${prefix}-24-milestone-square.png`) });
  const square = await milestone.boundingBox();
  assert.ok(square && Math.abs(square.width - square.height) < 1, 'Square card must be 1:1');
  fs.writeFileSync(path.join(output, `${prefix}-console.json`), JSON.stringify(logs, null, 2));
  assert.equal(logs.length, 0, logs.join('\n'));
  console.log(`${scheme}: walkthrough passed with no console errors`);
  } catch (error) {
    await page.screenshot({ path: path.join(output, `${prefix}-failure.png`) });
    console.error(logs.join('\n'));
    throw error;
  } finally {
    await browser.close();
  }
})().catch((e) => { console.error('FLOW ERROR', e.message); process.exit(1); });
